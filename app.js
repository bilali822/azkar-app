let cachedPrayerTimes = null;
let countdownInterval = null;

function loadPrayerTimes() {
  if (typeof adhan === 'undefined') return;
  
  const grid = document.getElementById('prayerTimesGrid');
  if (!grid) return;
  grid.innerHTML = '<div style="text-align:center; padding:20px; color:var(--text-muted);">جارٍ حساب المواقيت...</div>';

  const fallbackCoords = { lat: 21.4225, lng: 39.8262 }; // مكة المكرمة

  const computeTimes = (lat, lng) => {
    try {
      const coordinates = new adhan.Coordinates(lat, lng);
      const params = adhan.CalculationMethod.UmmAlQura();
      const date = new Date();
      const times = new adhan.PrayerTimes(coordinates, date, params);

      cachedPrayerTimes = {
        fajr: times.fajr, sunrise: times.sunrise, dhuhr: times.dhuhr,
        asr: times.asr, maghrib: times.maghrib, isha: times.isha
      };

      const order = ['fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha'];
      const names = { fajr: 'الفجر', sunrise: 'الشروق', dhuhr: 'الظهر', asr: 'العصر', maghrib: 'المغرب', isha: 'العشاء' };

      grid.innerHTML = order.map(key => {
        const t = cachedPrayerTimes[key];
        const timeStr = t.toLocaleTimeString('ar-SA', { hour: '2-digit', minute: '2-digit', hour12: true });
        return `<div class="prayer-time-row" data-prayer="${key}">
          <span class="prayer-time-name">${names[key]}</span>
          <span class="prayer-time-value">${timeStr}</span>
        </div>`;
      }).join('');

      updateCountdown();
      if (countdownInterval) clearInterval(countdownInterval);
      countdownInterval = setInterval(updateCountdown, 1000);
    } catch (e) {
      grid.innerHTML = '<div style="text-align:center; padding:20px; color:var(--text-muted);">تعذر حساب المواقيت.</div>';
    }
  };

  if (window.Capacitor && window.Capacitor.Plugins.Geolocation) {
    window.Capacitor.Plugins.Geolocation.getCurrentPosition({ enableHighAccuracy: true })
      .then(pos => computeTimes(pos.coords.latitude, pos.coords.longitude))
      .catch(() => computeTimes(fallbackCoords.lat, fallbackCoords.lng));
  } else if (navigator.geolocation) {
    navigator.geolocation.getCurrentPosition(
      pos => computeTimes(pos.coords.latitude, pos.coords.longitude),
      () => computeTimes(fallbackCoords.lat, fallbackCoords.lng),
      { timeout: 5000 }
    );
  } else {
    computeTimes(fallbackCoords.lat, fallbackCoords.lng);
  }
}

function updateCountdown() {
  if (!cachedPrayerTimes) return;
  const now = new Date();
  const order = ['fajr', 'dhuhr', 'asr', 'maghrib', 'isha'];
  let nextKey = null;
  let nextTime = null;

  for (const key of order) {
    if (cachedPrayerTimes[key] > now) {
      nextKey = key;
      nextTime = cachedPrayerTimes[key];
      break;
    }
  }

  if (!nextKey) {
    // إذا انتهت صلوات اليوم، الصلاة القادمة هي فجر الغد
    const tomorrow = new Date(now);
    tomorrow.setDate(tomorrow.getDate() + 1);
    const t = new adhan.PrayerTimes(new adhan.Coordinates(21.4225, 39.8262), tomorrow, adhan.CalculationMethod.UmmAlQura());
    nextKey = 'fajr';
    nextTime = t.fajr;
  }

  const diff = nextTime - now;
  const h = Math.floor(diff / 3600000);
  const m = Math.floor((diff % 3600000) / 60000);
  const s = Math.floor((diff % 60000) / 1000);

  const names = { fajr: 'الفجر', dhuhr: 'الظهر', asr: 'العصر', maghrib: 'المغرب', isha: 'العشاء' };

  const nameEl = document.getElementById('nextPrayerName');
  const timerEl = document.getElementById('countdownTimer');
  const timeEl = document.getElementById('nextPrayerTime');
  
  if (nameEl && timerEl && timeEl) {
    nameEl.textContent = names[nextKey];
    timerEl.textContent = `${String(h).padStart(2,'0')}:${String(m).padStart(2,'0')}:${String(s).padStart(2,'0')}`;
    timeEl.textContent = nextTime.toLocaleTimeString('ar-SA', { hour: '2-digit', minute: '2-digit', hour12: true });
  }

  document.querySelectorAll('.prayer-time-row').forEach(row => {
    row.classList.toggle('current', row.dataset.prayer === nextKey);
  });
}

